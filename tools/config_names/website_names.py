"""Writes the website's game names (src/website/internal/gamenames/names_gen.go)
from the mission config, so the Admin Panel can show "Offroad" / "Driver
Licence" / "Copper Ore" instead of classnames:

  - vehicles: the shop rows in CfgVehicles.hpp (the row's own name, else
    Arma's -- names.json, from arma_names.py -- else its "// <name>" comment)
  - licences: CfgLicences displayName
  - items (vItems, e.g. in vehicle trunks): CfgItems displayName
  - crimes: CfgCrimes name
  - gear: Arma's names (names.json) for every classname the config mentions

Re-run after adding vehicles, licences or items:

    python tools/config_names/website_names.py
"""
import json
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
CFG = os.path.join(ROOT, "src", "ALife.Altis", "config")
OUT = os.path.join(ROOT, "src", "website", "internal", "gamenames", "names_gen.go")


def read(name):
    return open(os.path.join(CFG, name), encoding="utf-8").read()


# Arma's own names (arma_names.py output), then the shop row's own name,
# then its "// <name>" comment (without any " -- note").
arma = json.load(open(os.path.join(HERE, "names.json"), encoding="utf-8"))
vehicles = {}
for line in read("CfgVehicles.hpp").splitlines():
    m = re.match(r'\s*\{\s*"(\w+)"\s*,\s*"([^"]*)"\s*,\s*\d', line) or re.match(r"\s*class (\w+)\s*\{\s*trunk()", line)
    if not m:
        continue
    key = m.group(1).lower()
    comment = line.split("//", 1)[1].split(" -- ")[0].strip() if "//" in line else ""
    name = m.group(2) or arma.get(key) or comment
    if name and key not in vehicles:
        vehicles[key] = name


def display_names(text):
    out = {}
    cur = None
    for line in text.splitlines():
        m = re.match(r"\s*class (\w+)\b", line)
        if m:
            cur = m.group(1)
        m = re.search(r'displayName = "([^"]*)"', line)
        if m and cur:
            out[cur.lower()] = m.group(1)
    return out


licences = display_names(read("CfgLicences.hpp"))
items = display_names(read("CfgItems.hpp"))

# Licences in config order with their faction (the "// Police" / "// EMS"
# section comments in CfgLicences.hpp; everything before is civilian).
licence_list = []
side = "civ"
for line in read("CfgLicences.hpp").splitlines():
    c = line.strip()
    if c.startswith("// Police"):
        side = "cop"
    elif c.startswith("// EMS"):
        side = "medic"
    m = re.match(r'\s*class (\w+)\s*\{\s*displayName = "([^"]*)"', line)
    if m:
        licence_list.append((m.group(1), m.group(2), side))

crimes = {}
for m in re.finditer(r'class (\w+)\s*\{\s*name = "([^"]*)"', read("CfgCrimes.hpp")):
    crimes[m.group(1).lower()] = m.group(2)

# Arma gear (weapons, clothing, attachments, magazines, items) the mission
# mentions anywhere in its config, by Arma's own name -- for the loadouts
# the Admin Panel shows. Anything else falls back to its classname.
gear = {}
for name in sorted(os.listdir(CFG)):
    if name.endswith(".hpp"):
        for cls in re.findall(r'"([A-Za-z0-9][A-Za-z0-9_]{2,})"', read(name)):  # (magazines start with a digit)
            n = arma.get(cls.lower())
            if n and cls.lower() not in vehicles:
                gear[cls.lower()] = n


def go_str(s):
    # Arma's names use non-breaking spaces ("MX 6.5 mm"); plain ones read the same.
    return json.dumps(s.replace(" ", " "), ensure_ascii=False)


def go_map(name, d):
    rows = "".join(f"\t{go_str(k)}: {go_str(v)},\n" for k, v in sorted(d.items()))
    return f"var {name} = map[string]string{{\n{rows}}}\n"


for d in (vehicles, licences, items, crimes, gear):
    for k, v in d.items():
        assert '"' not in v and "\\" not in v, v

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Code generated by tools/config_names/website_names.py from the mission config. DO NOT EDIT.\n\n")
    f.write("package gamenames\n\n")
    f.write(go_map("vehicles", vehicles) + "\n" + go_map("licences", licences) + "\n" + go_map("items", items))
    f.write("\n" + go_map("crimes", crimes) + "\n" + go_map("gear", gear))
    rows = "".join(f'\t{{Key: "{k}", Name: "{n}", Side: "{sd}"}},\n' for k, n, sd in licence_list)
    f.write(f"\nvar licenceList = []LicenceDef{{\n{rows}}}\n")
subprocess.run(["gofmt", "-w", OUT], check=True)
print(f"{len(vehicles)} vehicles, {len(licences)} licences, {len(items)} items, {len(crimes)} crimes, {len(gear)} gear -> {OUT}")
